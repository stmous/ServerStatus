#!/usr/bin/env bash
# Idempotent InfluxDB 2.x bootstrap for serverroom-monitor.
#
# Creates (or updates) the org, the raw and downsampled buckets with their
# retention, the downsampling task, and two least-privilege tokens:
#   serverroom-collector  write-only on the raw bucket
#   serverroom-grafana    read-only on both buckets
# and prints them as KEY=VALUE lines on stdout for the installer to store.
#
# Required environment:
#   INFLUX_HOST            e.g. http://127.0.0.1:8086
#   INFLUX_ORG, INFLUX_BUCKET, INFLUX_BUCKET_DS
#   RETENTION_RAW_S, RETENTION_DS_S   retention in seconds
#   INFLUX_ADMIN_PASSWORD  used only for the initial setup
#   INFLUX_OPERATOR_TOKEN  all-access operator token (set at initial setup)
# Optional:
#   INFLUX_CLI             path to the influx CLI (default: influx)
#   TASK_TEMPLATE          path to downsample_5m.flux
set -euo pipefail

: "${INFLUX_HOST:?}" "${INFLUX_ORG:?}" "${INFLUX_BUCKET:?}" "${INFLUX_BUCKET_DS:?}"
: "${RETENTION_RAW_S:?}" "${RETENTION_DS_S:?}" "${INFLUX_OPERATOR_TOKEN:?}"
INFLUX_CLI=${INFLUX_CLI:-influx}
HERE=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
TASK_TEMPLATE=${TASK_TEMPLATE:-$HERE/tasks/downsample_5m.flux}
TASK_NAME=serverroom-downsample-5m

log() { printf '[influxdb] %s\n' "$*" >&2; }
die() { log "ERROR: $*"; exit 1; }

# Never put the token on a command line (visible in ps): use the env var
# the CLI reads, and a throwaway config dir so no state leaks into ~/.influxdbv2.
export INFLUX_HOST
export INFLUX_TOKEN=$INFLUX_OPERATOR_TOKEN
INFLUX_CONFIGS_PATH=$(mktemp)
export INFLUX_CONFIGS_PATH
trap 'rm -f "$INFLUX_CONFIGS_PATH"' EXIT

cli() { "$INFLUX_CLI" "$@"; }

# --- wait for the server ------------------------------------------------------
for _ in $(seq 1 60); do
    if curl -fsS "$INFLUX_HOST/health" >/dev/null 2>&1; then break; fi
    sleep 1
done
curl -fsS "$INFLUX_HOST/health" >/dev/null || die "InfluxDB not reachable at $INFLUX_HOST"

# --- initial setup (only on a fresh instance) ---------------------------------
if curl -fsS "$INFLUX_HOST/api/v2/setup" | grep -q '"allowed": *true'; then
    : "${INFLUX_ADMIN_PASSWORD:?needed for initial setup}"
    log "running initial setup (org $INFLUX_ORG)"
    # The operator token is generated by the installer and supplied here, so
    # it is known before setup and never has to be scraped from output.
    INFLUX_TOKEN='' cli setup --force \
        --username admin --password "$INFLUX_ADMIN_PASSWORD" \
        --org "$INFLUX_ORG" --bucket "$INFLUX_BUCKET" \
        --retention "${RETENTION_RAW_S}s" --token "$INFLUX_OPERATOR_TOKEN" >/dev/null
fi

cli ping >/dev/null 2>&1 || true
if ! cli org list --name "$INFLUX_ORG" --hide-headers >/dev/null 2>&1; then
    die "operator token rejected or org '$INFLUX_ORG' missing. If secrets.env was lost, the
       instance must be reset (see README: 'Lost InfluxDB operator token')."
fi

# --- buckets ------------------------------------------------------------------
bucket_id() {
    # "bucket list --name" exits non-zero when the bucket does not exist.
    { cli bucket list --org "$INFLUX_ORG" --name "$1" --hide-headers 2>/dev/null || true; } |
        awk '{print $1}'
}

ensure_bucket() {
    local name=$1 retention_s=$2 id
    id=$(bucket_id "$name")
    if [[ -z $id ]]; then
        log "creating bucket $name (retention ${retention_s}s)"
        cli bucket create --org "$INFLUX_ORG" --name "$name" --retention "${retention_s}s" >/dev/null
    else
        cli bucket update --id "$id" --retention "${retention_s}s" >/dev/null
    fi
}

ensure_bucket "$INFLUX_BUCKET" "$RETENTION_RAW_S"
ensure_bucket "$INFLUX_BUCKET_DS" "$RETENTION_DS_S"
RAW_ID=$(bucket_id "$INFLUX_BUCKET")
DS_ID=$(bucket_id "$INFLUX_BUCKET_DS")
[[ -n $RAW_ID && -n $DS_ID ]] || die "bucket lookup failed"

# --- downsampling task --------------------------------------------------------
TASK_FILE=$(mktemp --suffix=.flux)
trap 'rm -f "$INFLUX_CONFIGS_PATH" "$TASK_FILE"' EXIT
sed -e "s|@RAW_BUCKET@|$INFLUX_BUCKET|g" -e "s|@DS_BUCKET@|$INFLUX_BUCKET_DS|g" \
    -e "s|@ORG@|$INFLUX_ORG|g" "$TASK_TEMPLATE" >"$TASK_FILE"

task_id=$(cli task list --org "$INFLUX_ORG" --json |
    python3 -c 'import json,sys; print(next((t["id"] for t in json.load(sys.stdin) if t["name"]==sys.argv[1]), ""))' "$TASK_NAME")
if [[ -z $task_id ]]; then
    log "creating task $TASK_NAME"
    cli task create --org "$INFLUX_ORG" --file "$TASK_FILE" >/dev/null
else
    cli task update --id "$task_id" --file "$TASK_FILE" >/dev/null
    cli task update --id "$task_id" --status active >/dev/null
fi

# --- tokens -------------------------------------------------------------------
# Find a token by description; create it with the given permissions if missing.
token_for() {
    local description=$1
    shift
    local token
    token=$(cli auth list --org "$INFLUX_ORG" --json |
        python3 -c 'import json,sys
for a in json.load(sys.stdin):
    if a.get("description")==sys.argv[1] and a.get("status","active")=="active":
        print(a["token"]); break' "$description")
    if [[ -z $token ]]; then
        log "creating token '$description'"
        token=$(cli auth create --org "$INFLUX_ORG" --description "$description" "$@" --json |
            python3 -c 'import json,sys; print(json.load(sys.stdin)["token"])')
    fi
    printf '%s' "$token"
}

WRITE_TOKEN=$(token_for serverroom-collector --write-bucket "$RAW_ID")
READ_TOKEN=$(token_for serverroom-grafana --read-bucket "$RAW_ID" --read-bucket "$DS_ID")

printf 'INFLUX_WRITE_TOKEN=%s\n' "$WRITE_TOKEN"
printf 'INFLUX_READ_TOKEN=%s\n' "$READ_TOKEN"
log "done"
