"""Write the Grafana provisioning tree and settings derived from config.yaml.

Output layout (``out`` is /etc/serverroom-monitor/generated on the Pi)::

    out/grafana-settings.env            non-secret GF_* settings for grafana-server
    out/kiosk.env                       settings for the kiosk launcher
    out/dashboards/server-room.json
    out/provisioning/datasources/serverroom.yaml
    out/provisioning/dashboards/serverroom.yaml
    out/provisioning/alerting/{templates-and-contact-points,policies,rules}.yaml
    out/provisioning/plugins/           (empty; avoids a startup warning)
"""

from __future__ import annotations

import json
import os
import tempfile
from pathlib import Path
from typing import Any

import yaml

from serverroom_monitor.config import Config
from serverroom_monitor.grafana.alerting import build_contact_points, build_policies, build_rules
from serverroom_monitor.grafana.dashboard import DASHBOARD_UID, build_dashboard
from serverroom_monitor.grafana.flux import DATASOURCE_UID

HEADER = "# Generated by `serverroom-monitor render-grafana` from config.yaml. Do not edit.\n"


def datasource(cfg: Config) -> dict[str, Any]:
    return {
        "apiVersion": 1,
        "datasources": [
            {
                "name": "InfluxDB (server room)",
                "uid": DATASOURCE_UID,
                "type": "influxdb",
                "access": "proxy",
                "url": cfg.influxdb.url,
                "isDefault": True,
                "editable": False,
                "jsonData": {
                    "version": "Flux",
                    "organization": cfg.influxdb.org,
                    "defaultBucket": cfg.influxdb.bucket,
                    "timeout": 30,
                },
                # Read-only token, expanded from grafana-server's environment.
                "secureJsonData": {"token": "${INFLUX_READ_TOKEN}"},
            }
        ],
    }


def dashboard_provider(dashboards_dir: Path) -> dict[str, Any]:
    return {
        "apiVersion": 1,
        "providers": [
            {
                "name": "serverroom",
                "orgId": 1,
                "folder": "Server Room",
                "type": "file",
                "disableDeletion": True,
                "allowUiUpdates": False,
                "updateIntervalSeconds": 60,
                "options": {"path": str(dashboards_dir), "foldersFromFilesStructure": False},
            }
        ],
    }


def grafana_settings(cfg: Config, provisioning_dir: Path, root_url: str | None) -> dict[str, str]:
    """GF_* environment overrides (non-secret). Secrets come from env/grafana.env."""
    g = cfg.grafana
    email = cfg.notifications.email
    starttls = {
        "mandatory": "MandatoryStartTLS",
        "opportunistic": "OpportunisticStartTLS",
        "none": "NoStartTLS",
    }[email.starttls]
    settings = {
        "GF_PATHS_PROVISIONING": str(provisioning_dir),
        # Localhost only unless LAN access is explicitly enabled; remote
        # access goes through `tailscale serve` which connects to localhost.
        "GF_SERVER_HTTP_ADDR": "0.0.0.0" if g.lan_access else "127.0.0.1",  # noqa: S104
        "GF_SERVER_HTTP_PORT": str(g.port),
        "GF_SERVER_ENFORCE_DOMAIN": "false",
        "GF_AUTH_ANONYMOUS_ENABLED": "false",
        "GF_AUTH_BASIC_ENABLED": "true",
        "GF_USERS_ALLOW_SIGN_UP": "false",
        "GF_USERS_ALLOW_ORG_CREATE": "false",
        "GF_USERS_DEFAULT_THEME": cfg.display.hdmi.theme,
        "GF_SECURITY_ADMIN_USER": "admin",
        "GF_SECURITY_DISABLE_GRAVATAR": "true",
        "GF_SECURITY_COOKIE_SAMESITE": "lax",
        # Plain-HTTP LAN logins would break with secure cookies; Tailscale
        # serve and localhost are both secure contexts.
        "GF_SECURITY_COOKIE_SECURE": "false" if g.lan_access else "true",
        "GF_SECURITY_ALLOW_EMBEDDING": "false",
        "GF_ANALYTICS_REPORTING_ENABLED": "false",
        "GF_ANALYTICS_CHECK_FOR_UPDATES": "false",
        "GF_ANALYTICS_CHECK_FOR_PLUGIN_UPDATES": "false",
        "GF_NEWS_NEWS_FEED_ENABLED": "false",
        "GF_DASHBOARDS_MIN_REFRESH_INTERVAL": "10s",
        "GF_PUBLIC_DASHBOARDS_ENABLED": "true",
        # Grafana 13 ships InfluxDB as a separately downloaded plugin. Install
        # it *before* startup (not in the background) so provisioning and the
        # first alert evaluations have it, and don't re-check for plugin
        # updates on every restart: that needs internet and changes behaviour
        # unattended (upgrade Grafana deliberately instead, see README).
        "GF_PLUGINS_PREINSTALL_SYNC": "influxdb",
        "GF_PLUGINS_PREINSTALL_AUTO_UPDATE": "false",
        "GF_UNIFIED_ALERTING_ENABLED": "true",
        "GF_DATABASE_WAL": "true",
        "GF_LOG_MODE": "console",
        "GF_LOG_LEVEL": "warn",
        "GF_SMTP_ENABLED": "true" if email.enabled else "false",
    }
    if root_url:
        settings["GF_SERVER_ROOT_URL"] = root_url
    if email.enabled:
        settings.update(
            {
                "GF_SMTP_HOST": f"{email.smtp_host}:{email.smtp_port}",
                "GF_SMTP_USER": email.smtp_user,
                "GF_SMTP_FROM_ADDRESS": email.from_address,
                "GF_SMTP_FROM_NAME": email.from_name,
                "GF_SMTP_STARTTLS_POLICY": starttls,
            }
        )
    return settings


def kiosk_settings(cfg: Config) -> dict[str, str]:
    h = cfg.display.hdmi
    return {
        "KIOSK_ENABLED": "1" if cfg.display.mode == "hdmi" else "0",
        "KIOSK_SESSION": h.session,
        "KIOSK_ROTATION": str(h.rotation),
        "KIOSK_SCREEN_BLANKING": "1" if h.screen_blanking else "0",
        "KIOSK_BLANK_AFTER": str(int(h.blank_after)),
        "KIOSK_THEME": h.theme,
        "KIOSK_GRAFANA_URL": cfg.grafana.url,
        "KIOSK_DASHBOARD_UID": DASHBOARD_UID,
    }


def _env_file(values: dict[str, str]) -> str:
    lines = []
    for key, value in values.items():
        escaped = value.replace("\\", "\\\\").replace('"', '\\"')
        lines.append(f'{key}="{escaped}"')
    return HEADER + "\n".join(lines) + "\n"


class _Dumper(yaml.SafeDumper):
    """Emit multi-line strings (Flux queries, templates) as readable ``|`` blocks."""


def _str_presenter(dumper: yaml.SafeDumper, data: str) -> yaml.ScalarNode:
    style = "|" if "\n" in data else None
    return dumper.represent_scalar("tag:yaml.org,2002:str", data, style=style)


_Dumper.add_representer(str, _str_presenter)


def _yaml(doc: dict[str, Any]) -> str:
    body = yaml.dump(doc, Dumper=_Dumper, sort_keys=False, allow_unicode=True, width=1000)
    return HEADER + body


def _write(path: Path, content: str) -> None:
    """Atomic write, so Grafana never sees a half-written provisioning file."""
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(dir=path.parent, prefix=f".{path.name}.")
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as fh:
            fh.write(content)
        Path(tmp).chmod(0o644)
        Path(tmp).replace(path)
    except BaseException:
        Path(tmp).unlink(missing_ok=True)
        raise


DEPLOY_ROOT = Path("/etc/serverroom-monitor/generated")


def render_all(
    cfg: Config, out: Path, root_url: str | None = None, deploy_root: Path | None = None
) -> list[Path]:
    """Render into ``out``. Paths written *inside* the files point at
    ``deploy_root`` (default: ``out`` itself), so the repo's reference copy can
    be rendered with the paths used on the Pi."""
    out = out.resolve()
    root = deploy_root or out
    prov = out / "provisioning"
    dashboards = out / "dashboards"
    files: dict[Path, str] = {
        out / "grafana-settings.env": _env_file(
            grafana_settings(cfg, root / "provisioning", root_url)
        ),
        out / "kiosk.env": _env_file(kiosk_settings(cfg)),
        dashboards / "server-room.json": json.dumps(build_dashboard(cfg), indent=2) + "\n",
        prov / "datasources" / "serverroom.yaml": _yaml(datasource(cfg)),
        prov / "dashboards" / "serverroom.yaml": _yaml(dashboard_provider(root / "dashboards")),
        prov / "alerting" / "contact-points.yaml": _yaml(build_contact_points(cfg)),
        prov / "alerting" / "policies.yaml": _yaml(build_policies(cfg)),
        prov / "alerting" / "rules.yaml": _yaml(build_rules(cfg)),
    }
    (prov / "plugins").mkdir(parents=True, exist_ok=True)
    for path, content in files.items():
        _write(path, content)
    return sorted(files)
